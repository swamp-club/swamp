/**
 * Installs swamp's Zod module on globalThis so that extension bundles
 * with externalized `import { z } from "npm:zod@4"` (rewritten to
 * `const { z } = globalThis.__swamp_zod`) share the same Zod instance.
 *
 * This prevents dual-instance problems in the compiled binary where
 * `deno compile` resolves dynamic imports to a separate module instance.
 */
export function installZodGlobal(): void {
  if (!globalThis.__swamp_zod) {
    globalThis.__swamp_zod = zodModule;
    logger.debug`Installed Zod global (globalThis.__swamp_zod)`;
  }
}

/**
 * Converts a Uint8Array to a base64 string without blowing the call stack.
 *
 * The naive `btoa(String.fromCharCode(...bytes))` spreads every byte onto
 * the call stack as a function argument, which causes `RangeError: Maximum
 * call stack size exceeded` for large bundles (e.g., extensions with inlined
 * npm packages like @octokit/rest or @slack/web-api).
 *
 * This function processes bytes in fixed-size chunks to stay well within
 * V8's call-stack limits regardless of bundle size.
 */
export function uint8ArrayToBase64(bytes: Uint8Array): string {
  const CHUNK_SIZE = 8192;
  let binary = "";
  for (let i = 0; i < bytes.length; i += CHUNK_SIZE) {
    const chunk = bytes.subarray(i, i + CHUNK_SIZE);
    binary += String.fromCharCode(...chunk);
  }
  return btoa(binary);
}

/**
 * Fixes CJS/ESM interop in bundles generated by `deno bundle` (esbuild).
 *
 * esbuild generates a `__toESM` helper that conditionally sets a `.default`
 * property on the wrapper object. When `--platform deno` is used, the
 * `isNodeMode` flag is false, so CJS modules that set `module.exports.__esModule = true`
 * (like tslib) don't get a `.default` property. Code that then destructures
 * `import_tslib.default` gets `undefined`, causing runtime crashes.
 *
 * This fix changes the `__toESM` helper to always set `.default`, which matches
 * the behavior of `--platform node` and is correct for Deno's Node compat layer.
 */
export function fixCjsEsmInterop(js: string): string {
  // Match the esbuild-generated __toESM ternary condition.
  // Original: `isNodeMode || !mod || !mod.__esModule ? __defProp(target, "default", ...) : target`
  // Fixed: always set .default (drop the `: target` fallback)
  return js.replace(
    /isNodeMode \|\| !mod \|\| !mod\.__esModule \? (__defProp\(target, "default", \{ value: mod, enumerable: true \}\)) : target/,
    "$1",
  );
}

/**
 * Truncates data URLs in error messages to avoid flooding the terminal
 * with megabytes of base64-encoded bundle content.
 */
export function sanitizeDataUrlError(error: unknown): string {
  const message = String(error);
  return message.replace(
    /data:application\/javascript;base64,[A-Za-z0-9+/=]{100,}/g,
    "data:application/javascript;base64,[truncated]",
  );
}

// Syntax esbuild can leave in a bundle that Babel does not parse by default.
const BUNDLE_PARSER_PLUGINS: ParserPlugin[] = [
  "importAttributes",
  "explicitResourceManagement",
  "decorators",
  "decoratorAutoAccessors",
  "sourcePhaseImports",
  "deferredImportEvaluation",
];

/** One import declaration in a bundle: its text span and its specifier. */
interface ImportDeclarationSpan {
  start: number;
  end: number;
  specifier: string;
}

/**
 * Finds the import declarations of a bundle by parsing it, so import text
 * inside a string, template literal, comment or regex literal is never
 * reported (swamp-club#3072 — an extension that generates TypeScript carries
 * such text as data). Import declarations are only legal at the top level of
 * a module, so `program.body` is the whole search space.
 *
 * Throws when the bundle does not parse. Callers reach this only after a text
 * match, and without a parse there is no telling a real import from generated
 * text — guessing either way silently breaks the extension.
 *
 * @param origin - The bundle or source path, named in the error when known.
 *   The error says "the extension at", so either kind of path reads right.
 */
function findImportDeclarations(
  js: string,
  origin?: string,
): ImportDeclarationSpan[] {
  let body;
  try {
    body = parse(js, {
      sourceType: "module",
      plugins: BUNDLE_PARSER_PLUGINS,
      allowReturnOutsideFunction: true,
      allowAwaitOutsideFunction: true,
      allowUndeclaredExports: true,
      allowNewTargetOutsideFunction: true,
      allowSuperOutsideMethod: true,
      errorRecovery: true,
    }).program.body;
  } catch (error) {
    // Syntax errors, and stack overflow on extreme nesting.
    const reason = error instanceof Error ? error.message : String(error);
    throw markErrorPaths(
      new UserError(
        `Cannot load the extension${origin ? ` at ${origin}` : ""}: its ` +
          `bundle holds text that looks like a zod import, and swamp could ` +
          `not parse the bundle to tell a real import from generated text ` +
          `(${reason}). A cached bundle may be damaged — delete it so swamp ` +
          `rebuilds it from the extension source, or pull the extension ` +
          `again. If the error remains, the extension uses syntax swamp's ` +
          `bundle parser does not support: report it with ` +
          `\`swamp issue bug\` and include this message.`,
        "bundle_parse_failed",
      ),
      [origin],
    );
  }

  const spans: ImportDeclarationSpan[] = [];
  for (const node of body) {
    if (node.type !== "ImportDeclaration") continue;
    if (typeof node.start !== "number" || typeof node.end !== "number") {
      continue;
    }
    spans.push({
      start: node.start,
      end: node.end,
      specifier: node.source.value,
    });
  }
  return spans;
}

/**
 * Whether every version `version` admits has major `major`: an exact
 * version or a range such as `^4`, `~4.2` or `>=4.1 <5`.
 */
function versionWithinMajor(version: string, major: number): boolean {
  const range = tryParseRange(version);
  if (!range) return false;
  // A prerelease of `major` (4.0.0-beta.1) counts; the next major's
  // prereleases are left out, as `<5.0.0` itself leaves them in.
  return rangeIntersects(
    range,
    parseRange(`>=${major}.0.0-0 <${major + 1}.0.0`),
  ) &&
    !rangeIntersects(range, parseRange(`<${major}.0.0-0`)) &&
    !rangeIntersects(range, parseRange(`>=${major + 1}.0.0`));
}

/**
 * The version a zod specifier writes, without a subpath a versioned
 * specifier may carry (`npm:zod@4.3.6/v4` is `4.3.6`); null when
 * unversioned, undefined when it is not zod.
 */
function zodSpecifierVersion(specifier: string): string | null | undefined {
  const match = /^(?:npm:)?zod(?:@([^/]+)(?:\/.*)?)?$/.exec(specifier);
  if (!match) return undefined;
  return match[1] ?? null;
}

/**
 * Whether an import of `specifier` gets the host's zod 4: `zod`, `npm:zod`,
 * or a version or range every admitted version of which is 4.x (`npm:zod@4`,
 * `npm:zod@4.3.6`, `npm:zod@^4.1`, `npm:zod@~4.2`). Push can ship any of
 * these, rewritten from an import-map target (swamp-club#3637).
 */
export function isZod4Specifier(specifier: string): boolean {
  const version = zodSpecifierVersion(specifier);
  if (version === undefined) return false;
  return version === null || versionWithinMajor(version, 4);
}

/** Whether `specifier` imports zod 3 at every version it admits. */
export function isZod3Specifier(specifier: string): boolean {
  const version = zodSpecifierVersion(specifier);
  return typeof version === "string" && versionWithinMajor(version, 3);
}

// An import declaration whose specifier names zod at some version; the
// specifier is checked with isZod3Specifier.
const ZOD_VERSIONED_IMPORT_RE =
  /import\s+(?:\{[^}]+\}|\*\s+as\s+\w+)\s+from\s*["']((?:npm:)?zod@[^"']*)["']/;

/**
 * Detects Zod v3 imports in bundled JS and throws with upgrade guidance.
 * Swamp ships Zod v4 — extensions using v3 will have broken schema
 * introspection and should upgrade. Only import declarations count: zod v3
 * import text inside a string or template literal is the extension's data.
 */
export function rejectZodV3Imports(js: string, origin?: string): void {
  if (!ZOD_VERSIONED_IMPORT_RE.test(js)) return;
  for (const { start, end } of findImportDeclarations(js, origin)) {
    const match = ZOD_VERSIONED_IMPORT_RE.exec(js.slice(start, end));
    if (match && isZod3Specifier(match[1])) {
      throw new UserError(
        `Extension imports Zod v3 (${match[0].trim()}). ` +
          `Swamp requires Zod v4 — update your zod dependency to v4 and ` +
          `rebuild. See https://zod.dev/v4 for migration guidance.`,
      );
    }
  }
}

// Match: import { ... } from "npm:zod...", "zod", or 'zod'
// Handles both npm: prefixed specifiers (existing extensions) and
// bare "zod" specifiers (when externalized via deno.json import map).
// Matches any zod version but an obvious 3.x (so a cached zod 3 bundle is
// never parsed); only declarations whose specifier passes isZod4Specifier
// are rewritten — zod 3.x is detected separately at
// bundle-creation time via rejectZodV3Imports (not here, because
// rewriteZodImports is also called at runtime on cached bundles).
const ZOD_NAMED_IMPORT_RE =
  /import\s*\{([^}]+)\}\s*from\s*["'](?:npm:)?zod(?:@(?![\^~=v]?3)[^"']*)?["']\s*;?/g;

// Match: import * as <name> from "npm:zod..." or "zod"
const ZOD_STAR_IMPORT_RE =
  /import\s*\*\s*as\s+(\w+)\s+from\s*["'](?:npm:)?zod(?:@(?![\^~=v]?3)[^"']*)?["']\s*;?/g;

/** Rewrites the text of one zod import declaration. */
function rewriteZodImportDeclaration(declaration: string): string {
  return declaration
    .replace(ZOD_NAMED_IMPORT_RE, (_match, imports: string) => {
      // Convert `z as z2` to `z: z2` for destructuring syntax
      const destructured = imports
        .split(",")
        .map((s: string) => {
          const parts = s.trim().split(/\s+as\s+/);
          if (parts.length === 2) {
            return `${parts[0].trim()}: ${parts[1].trim()}`;
          }
          return parts[0].trim();
        })
        .filter((s: string) => s.length > 0)
        .join(", ");
      return `const { ${destructured} } = globalThis.__swamp_zod;`;
    })
    .replace(ZOD_STAR_IMPORT_RE, (_match, name: string) => {
      return `const ${name} = globalThis.__swamp_zod;`;
    });
}

/**
 * Rewrites externalized Zod imports in a bundle to reference `globalThis.__swamp_zod`.
 *
 * Handles:
 * - Named imports: `import { z } from "npm:zod@4"` → `const { z } = globalThis.__swamp_zod;`
 * - Aliased imports: `import { z as z2 } from "npm:zod"` → `const { z: z2 } = globalThis.__swamp_zod;`
 * - Star imports: `import * as zod from "npm:zod@4"` → `const zod = globalThis.__swamp_zod;`
 * - Already-rewritten lines are left untouched (idempotent).
 *
 * Only import declarations are rewritten. The same text inside a string,
 * template literal, comment or regex literal is left byte-identical.
 *
 * Throws when the bundle holds zod import text but does not parse.
 *
 * @param origin - The bundle or source path, named in that error when known
 */
export function rewriteZodImports(js: string, origin?: string): string {
  // Loaders call this on every cached bundle, nearly all of them already
  // rewritten — skip the parse unless there is something that could match.
  if (
    js.search(ZOD_NAMED_IMPORT_RE) === -1 &&
    js.search(ZOD_STAR_IMPORT_RE) === -1
  ) {
    return js;
  }

  const parts: string[] = [];
  let cursor = 0;
  for (
    const { start, end, specifier } of findImportDeclarations(js, origin)
  ) {
    if (!isZod4Specifier(specifier)) continue;
    parts.push(js.slice(cursor, start));
    parts.push(rewriteZodImportDeclaration(js.slice(start, end)));
    cursor = end;
  }
  if (cursor === 0) return js;
  parts.push(js.slice(cursor));
  return parts.join("");
}

/**
 * The flags that make a deno subcommand resolve modules the way the bundler
 * does: the project's deno.json, or its package.json and node_modules (run
 * with `cwd` at the package.json directory), or no project at all. Shared
 * with the module graph read, so push packages the modules it bundles.
 *
 * With `readOnlyLock`, the project's lockfile is never written: `--frozen`
 * when it has one (a lock that no longer satisfies a specifier fails rather
 * than being rewritten), `--no-lock` when it has none (so none is created).
 */
export function denoProjectArgs(
  options?: {
    denoConfigPath?: string;
    packageJsonDir?: string;
    readOnlyLock?: ReadOnlyLock;
  },
): string[] {
  const project = options?.denoConfigPath
    ? ["--config", options.denoConfigPath]
    : options?.packageJsonDir
    ? ["--node-modules-dir=auto"]
    : undefined;
  if (!project) return ["--no-lock", "--node-modules-dir=none"];
  if (!options?.readOnlyLock) return project;
  return [
    ...project,
    options.readOnlyLock.lockPath ? "--frozen" : "--no-lock",
  ];
}

/**
 * Bundle a project without writing its lockfile. `lockPath` is the lock the
 * project has, or undefined when it has none.
 */
export interface ReadOnlyLock {
  lockPath?: string;
}

/** Whether deno output names a lockfile `--frozen` refused to update. */
export function isStaleLockfile(output: string): boolean {
  return stripAnsiCode(output).includes("The lockfile is out of date");
}

/**
 * The error for a lockfile that no longer matches the project: push would
 * have to rewrite it, and it treats the author's lock as read-only. Names
 * the command that brings the lock up to date, and keeps the change list
 * from the deno output but not its `--frozen=false` hint.
 */
export function staleLockfileError(
  lockPath: string,
  entryPoint: string,
  project: { denoConfigPath?: string; packageJsonDir?: string },
  output: string,
): UserError {
  const projectFile = project.denoConfigPath ?? "package.json";
  const projectDir = project.denoConfigPath
    ? dirname(project.denoConfigPath)
    : project.packageJsonDir ?? dirname(lockPath);
  const plain = stripAnsiCode(output);
  const changesAt = plain.indexOf("changes:");
  const changes = changesAt >= 0 ? `\n${plain.slice(changesAt).trimEnd()}` : "";
  return markErrorPaths(
    new UserError(
      `${lockPath} is out of date with ${projectFile}, and push and quality ` +
        `never rewrite your lockfile. Run \`deno install --entrypoint ` +
        `${entryPoint}\` in ${projectDir}, commit the updated lock, and try ` +
        `again.${changes}`,
    ),
    [lockPath, projectFile, entryPoint, projectDir],
  );
}

/** Options for controlling bundle output. */
export interface BundleOptions {
  /**
   * When true, inline all dependencies (including zod) so the bundle is
   * fully self-contained — no network or shared module graph required.
   * Used for out-of-process execution (e.g., Docker containers).
   */
  selfContained?: boolean;

  /**
   * Absolute path to a deno.json project config. When provided, the bundler
   * uses `--config <path>` instead of `--no-lock`, so the project's import
   * map and lockfile govern dependency resolution.
   */
  denoConfigPath?: string;

  /**
   * Absolute path to a directory containing a package.json. When provided,
   * the bundler sets `cwd` on the subprocess so Deno auto-detects the
   * package.json and resolves bare specifiers from `node_modules/`.
   * Mutually exclusive with `denoConfigPath`.
   */
  packageJsonDir?: string;

  /**
   * Leave the project's lockfile untouched: bundle with `--frozen` when it
   * has one, so a stale lock fails with {@link staleLockfileError}, and with
   * `--no-lock` when it has none. Push and quality set this; local loading
   * does not.
   */
  readOnlyLock?: ReadOnlyLock;

  /**
   * Environment variables for the subprocess. When provided, the bundler
   * passes these as `env` to `Deno.Command`. Use this to set `DENO_DIR`
   * so the subprocess cache does not land in `$HOME/Library/Caches/deno/`
   * (which triggers macOS TCC prompts).
   */
  env?: Record<string, string>;

  /**
   * Abort signal forwarded to the subprocess. When aborted the child
   * process is killed and the returned promise rejects.
   */
  signal?: AbortSignal;
}

/**
 * Checks whether a TypeScript source file contains bare specifier imports
 * (e.g., `from "zod"`, `from "@aws-sdk/..."`) that require a deno.json
 * import map to resolve. Returns true if any bare specifier is found.
 *
 * The bundler recognizes these import kinds; all but "bare" reach
 * `deno bundle` unchanged and are resolved by it without an import map:
 *
 * - relative (`./foo`, `../bar`) — resolved by path
 * - npm: (`npm:zod@4`) — non-local, resolved and inlined by deno bundle
 * - jsr: (`jsr:@std/assert@1`) — non-local, resolved and inlined by deno bundle
 * - https: (`https://deno.land/std/...`) — non-local, resolved and inlined by deno bundle
 * - node: (`node:fs`) — built-in, passed through unchanged
 * - bare (`zod`, `@aws-sdk/...`) — requires a deno.json or package.json to resolve
 *
 * Used by runtime loaders to determine whether a cached bundle should be
 * preferred over re-bundling when no deno.json is available (pulled
 * extensions with bare specifiers would always fail to rebundle locally).
 */
const IMPORT_SPECIFIER_RE =
  /(?:import|export)\s+[^;()]*?from\s+["']([^"']+)["']/g;

export function isBareSpecifier(specifier: string): boolean {
  // A specifier carrying a `${...}` placeholder is interpolated at runtime, not
  // a package name. stripSourceComments already removes the common source of
  // these (generated code inside template literals), but `import x from
  // "${pkg}"` is valid TypeScript at the top level — double quotes do not
  // interpolate — so the classifier guards itself rather than trusting callers.
  if (specifier.includes("${")) return false;
  if (specifier.startsWith(".")) return false;
  if (specifier.startsWith("npm:")) return false;
  if (specifier.startsWith("jsr:")) return false;
  if (specifier.startsWith("https:")) return false;
  if (specifier.startsWith("http:")) return false;
  if (specifier.startsWith("node:")) return false;
  return true;
}

// See also: stripComments in extension_dependency_extractor.ts (import-line
// only) and stripCommentsAndStrings in extension_quality_checker.ts (strips
// both). This variant blanks comments and template literals while preserving
// ' and " string contents, so the import-specifier regex can still match real
// import strings — a specifier always lives in one of those two quote styles.
//
// Template literals are blanked because a static import specifier can never be
// one (`import x from `y`` is a SyntaxError), so an import statement between
// backticks is always generated code, not part of this module's own graph
// (swamp-club#1490 — the same false-positive lineage as #602 and #657). When a
// backtick has no closing partner — a regex literal, say, which this scanner
// cannot recognise — the span is re-emitted verbatim rather than blanked, so an
// unbalanced backtick degrades to a no-op instead of erasing the rest of the
// file from the caller's view.
//
// Every blanked character becomes a space and newlines stay, so an offset in
// the output is the same offset in `source` (findImportSpecifiers reads import
// spans from it, swamp-club#3637).
export function stripSourceComments(source: string): string {
  const result: string[] = [];
  let i = 0;

  while (i < source.length) {
    // Single-line comment — blank to end of line
    if (source[i] === "/" && i + 1 < source.length && source[i + 1] === "/") {
      result.push(" ", " ");
      i += 2;
      while (i < source.length && source[i] !== "\n") {
        result.push(" ");
        i++;
      }
      continue;
    }

    // Block comment — blank preserving newlines
    if (source[i] === "/" && i + 1 < source.length && source[i + 1] === "*") {
      result.push(" ", " ");
      i += 2;
      while (i < source.length) {
        if (
          source[i] === "*" && i + 1 < source.length &&
          source[i + 1] === "/"
        ) {
          result.push(" ", " ");
          i += 2;
          break;
        }
        result.push(source[i] === "\n" ? "\n" : " ");
        i++;
      }
      continue;
    }

    // Double-quoted string — preserve content (imports live here)
    if (source[i] === '"') {
      result.push(source[i]);
      i++;
      while (i < source.length && source[i] !== '"' && source[i] !== "\n") {
        if (source[i] === "\\") {
          result.push(source[i]);
          i++;
        }
        if (i < source.length) {
          result.push(source[i]);
          i++;
        }
      }
      if (i < source.length && source[i] === '"') {
        result.push(source[i]);
        i++;
      }
      continue;
    }

    // Single-quoted string — preserve content
    if (source[i] === "'") {
      result.push(source[i]);
      i++;
      while (i < source.length && source[i] !== "'" && source[i] !== "\n") {
        if (source[i] === "\\") {
          result.push(source[i]);
          i++;
        }
        if (i < source.length) {
          result.push(source[i]);
          i++;
        }
      }
      if (i < source.length && source[i] === "'") {
        result.push(source[i]);
        i++;
      }
      continue;
    }

    // Template literal — blank content
    if (source[i] === "`") {
      const span: string[] = [];
      const next = skipTemplateLiteral(source, i, span);
      if (next === null) {
        // Unterminated: the backtick was not a template after all. Keep the
        // remainder verbatim — byte-identical to leaving it unscanned.
        result.push(source.slice(i));
        break;
      }
      result.push(span.join(""));
      i = next;
      continue;
    }

    result.push(source[i]);
    i++;
  }

  return result.join("");
}

/** Blanks a character, keeping newlines so line positions do not drift. */
function blank(ch: string): string {
  return ch === "\n" ? "\n" : " ";
}

/**
 * Consumes the template literal opening at `start`, appending its blanked span
 * to `out`. Returns the index just past the closing backtick, or null when the
 * source ends first — the caller re-emits the span verbatim in that case.
 */
function skipTemplateLiteral(
  source: string,
  start: number,
  out: string[],
): number | null {
  out.push(" ");
  let i = start + 1;
  while (i < source.length) {
    const ch = source[i];
    if (ch === "\\") {
      out.push(" ");
      i++;
      if (i < source.length) {
        out.push(blank(source[i]));
        i++;
      }
      continue;
    }
    if (ch === "`") {
      out.push(" ");
      return i + 1;
    }
    if (ch === "$" && source[i + 1] === "{") {
      out.push(" ", " ");
      i = skipInterpolation(source, i + 2, out);
      continue;
    }
    out.push(blank(ch));
    i++;
  }
  return null;
}

/**
 * Consumes a `${...}` interpolation body starting just past the `${`. Counts
 * every brace so an object literal cannot close the interpolation early, and
 * delegates quotes and nested templates so their contents cannot either.
 */
function skipInterpolation(
  source: string,
  start: number,
  out: string[],
): number {
  let depth = 1;
  let i = start;
  while (i < source.length) {
    const ch = source[i];
    if (ch === "{") {
      depth++;
      out.push(" ");
      i++;
      continue;
    }
    if (ch === "}") {
      depth--;
      out.push(" ");
      i++;
      if (depth === 0) return i;
      continue;
    }
    if (ch === '"' || ch === "'") {
      i = skipQuoted(source, i, ch, out);
      continue;
    }
    if (ch === "`") {
      const next = skipTemplateLiteral(source, i, out);
      // A nested template that never closes means the enclosing one does not
      // either — hand the whole span back to the caller's verbatim fallback.
      if (next === null) return source.length;
      i = next;
      continue;
    }
    out.push(blank(ch));
    i++;
  }
  return i;
}

/**
 * Consumes a ' or " string inside an interpolation, blanking it so braces in
 * its content are not counted against the interpolation depth.
 */
function skipQuoted(
  source: string,
  start: number,
  quote: string,
  out: string[],
): number {
  out.push(" ");
  let i = start + 1;
  while (i < source.length && source[i] !== quote && source[i] !== "\n") {
    if (source[i] === "\\") {
      out.push(" ");
      i++;
      if (i >= source.length) break;
    }
    out.push(blank(source[i]));
    i++;
  }
  if (i < source.length && source[i] === quote) {
    out.push(" ");
    i++;
  }
  return i;
}

export function sourceHasBareSpecifiers(source: string): boolean {
  const stripped = stripSourceComments(source);
  for (const match of stripped.matchAll(IMPORT_SPECIFIER_RE)) {
    if (isBareSpecifier(match[1])) return true;
  }
  return false;
}

export function extractBareSpecifierNames(source: string): string[] {
  const bare = new Set<string>();
  const stripped = stripSourceComments(source);
  for (const match of stripped.matchAll(IMPORT_SPECIFIER_RE)) {
    if (isBareSpecifier(match[1])) bare.add(match[1]);
  }
  return [...bare];
}

/**
 * What an import map resolves a bare specifier to, when that target is an
 * explicit specifier an author can write in its place (`npm:`, `jsr:`, a
 * URL or a relative path). An exact key wins; otherwise the longest key
 * ending in `/` that prefixes the specifier, with the rest appended, as
 * import maps resolve. Undefined when the map has no usable entry.
 */
export function importMapTarget(
  specifier: string,
  imports: Record<string, string> | undefined,
): string | undefined {
  if (!imports) return undefined;
  let target: string | undefined = imports[specifier];
  if (target === undefined) {
    let bestKey = "";
    for (const key of Object.keys(imports)) {
      if (
        key.endsWith("/") && specifier.startsWith(key) &&
        key.length > bestKey.length
      ) {
        bestKey = key;
      }
    }
    if (bestKey) {
      target = imports[bestKey] + specifier.slice(bestKey.length);
    }
  }
  if (typeof target !== "string" || isBareSpecifier(target)) return undefined;
  return target;
}

/**
 * Determines whether a bundle failure is "expected" — i.e. a pulled extension
 * whose source contains bare specifiers but has no project config (deno.json /
 * deno.jsonc) to resolve them. In this case the failure is a known limitation,
 * not a user error, and the cached bundle should be used silently.
 *
 * Returns false (unexpected failure) when:
 * - A deno.json is available (bundling should have succeeded)
 * - The source has no bare specifiers (failure is not config-related)
 *
 * @param absolutePath - Absolute path to the source .ts file
 * @param repoDir - Repository root, used as the upward-search boundary
 */
export function isExpectedBundleFailure(
  absolutePath: string,
  repoDir?: string,
): boolean {
  // Walk up from the source file looking for deno.json / deno.jsonc.
  // If found, the project config should have resolved specifiers — failure
  // is unexpected.
  let dir = dirname(absolutePath);
  const root = resolve("/");
  while (dir !== root) {
    if (repoDir && resolve(dir) === resolve(repoDir)) break;
    for (const name of ["deno.json", "deno.jsonc"]) {
      try {
        Deno.statSync(join(dir, name));
        return false; // Config found — failure is unexpected
      } catch {
        // Not found — keep walking
      }
    }
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }

  // No config found — check if source actually needs one.
  try {
    const source = Deno.readTextFileSync(absolutePath);
    return sourceHasBareSpecifiers(source);
  } catch {
    return false; // Can't read source — treat as unexpected
  }
}

// A static, side-effect or literal dynamic import, or a re-export: the
// specifier each import or export statement names.
const IMPORTED_SPECIFIER_RE = /(?:\bfrom|\bimport)\s*\(?\s*["']([^"'\n]+)["']/g;

/** How many modules {@link zod4SpecifiersReachedFrom} reads at most. */
const MAX_ZOD_SCAN_MODULES = 2000;

/**
 * The `npm:zod` specifiers admitting only zod 4 that `entry` and the
 * modules it reaches through relative imports write, read as text with
 * comments and template literals blanked. Exact spellings, so `deno bundle
 * --external` matches each of them; no deno call. A module that cannot be
 * read is skipped: the bundler reports it. Reading stops after
 * {@link MAX_ZOD_SCAN_MODULES} modules; a zod import past that is inlined.
 */
export async function zod4SpecifiersReachedFrom(
  entry: string,
): Promise<string[]> {
  const found = new Set<string>();
  const seen = new Set<string>([entry]);
  const queue = [entry];
  while (queue.length > 0 && seen.size <= MAX_ZOD_SCAN_MODULES) {
    const path = queue.shift()!;
    let source: string;
    try {
      source = await Deno.readTextFile(path);
    } catch {
      continue;
    }
    for (
      const match of stripSourceComments(source).matchAll(
        IMPORTED_SPECIFIER_RE,
      )
    ) {
      const spec = match[1];
      if (spec.startsWith("npm:zod") && isZod4Specifier(spec)) {
        found.add(spec);
      } else if (spec.startsWith("./") || spec.startsWith("../")) {
        const target = resolve(dirname(path), spec);
        if (!seen.has(target) && /\.[cm]?[jt]sx?$/.test(target)) {
          seen.add(target);
          queue.push(target);
        }
      }
    }
  }
  return [...found].sort();
}

/**
 * Reads a deno.json import map and determines how "zod" is mapped.
 * If it maps to a zod 4.x npm specifier, returns the resolved specifier
 * (e.g., "npm:zod@4.3.6") so it can be externalized alongside the
 * standard patterns. Returns undefined if there's no zod mapping or
 * if it maps to a non-4.x version (which should be inlined, not
 * externalized, since globalThis.__swamp_zod provides zod 4).
 */
async function resolveZodFromConfig(
  denoConfigPath: string,
): Promise<string | undefined> {
  try {
    const raw = await Deno.readTextFile(denoConfigPath);
    const config = JSON.parse(raw);
    const imports = config.imports as Record<string, string> | undefined;
    if (!imports || typeof imports["zod"] !== "string") return undefined;

    const target = imports["zod"];
    // npm:zod at a version or range that admits only 4.x (npm:zod@4,
    // npm:zod@4.3.6, npm:zod@^4.1); bare "zod" would resolve to zod 3 or
    // to nothing otherwise.
    if (target.startsWith("npm:zod@") && isZod4Specifier(target)) {
      return target;
    }
    return undefined;
  } catch {
    return undefined;
  }
}

/**
 * Reads a package.json and checks whether zod is listed as a 4.x dependency.
 * Returns true if zod 4.x is found in dependencies or devDependencies.
 */
async function isZod4InPackageJson(
  packageJsonDir: string,
): Promise<boolean> {
  try {
    const raw = await Deno.readTextFile(join(packageJsonDir, "package.json"));
    const pkg = JSON.parse(raw);
    const deps: Record<string, string> = {
      ...pkg.dependencies,
      ...pkg.devDependencies,
    };
    const zodVersion = deps["zod"];
    if (!zodVersion) return false;
    // Match 4, 4.x.y, ^4, ~4, >=4, etc.
    return /^[\^~>=]*4(?:\.|$)/.test(zodVersion);
  } catch {
    return false;
  }
}

/**
 * Whether `deno bundle` output names a failed esbuild install: two bundles
 * started at once on a cache without esbuild both install it, and one can
 * fail copying the binary the other is writing.
 */
export function isEsbuildInstallRace(output: string): boolean {
  return output.includes("failed to copy esbuild binary");
}

/**
 * Runs `fn` alone for the first call per `key`; later calls wait for it to
 * settle, then run side by side. A first call that throws, or whose result
 * `succeeded` rejects, clears the key, so the next caller goes first in its
 * place. An abort of `signal` ends the wait with its reason.
 */
export async function runFirstAlone<T>(
  gates: Map<string, Promise<boolean>>,
  key: string,
  fn: () => Promise<T>,
  options: { signal?: AbortSignal; succeeded?: (result: T) => boolean } = {},
): Promise<T> {
  for (let gate = gates.get(key); gate; gate = gates.get(key)) {
    if (await abortable(gate, options.signal)) return await fn();
  }
  let settle!: (ok: boolean) => void;
  gates.set(key, new Promise<boolean>((resolve) => settle = resolve));
  let ok = false;
  try {
    const result = await fn();
    ok = options.succeeded?.(result) ?? true;
    return result;
  } finally {
    if (!ok) gates.delete(key);
    settle(ok);
  }
}

/** `promise`, or a rejection with the abort reason once `signal` aborts. */
function abortable<T>(promise: Promise<T>, signal?: AbortSignal): Promise<T> {
  if (signal === undefined) return promise;
  if (signal.aborted) return Promise.reject(signal.reason);
  return new Promise<T>((resolve, reject) => {
    const onAbort = () => reject(signal.reason);
    signal.addEventListener("abort", onAbort, { once: true });
    promise.then(resolve, reject).finally(() =>
      signal.removeEventListener("abort", onAbort)
    );
  });
}

/**
 * The first bundle per Deno cache in this process, which installs esbuild
 * into an empty cache and so must not race another bundle doing the same.
 */
const firstBundles = new Map<string, Promise<boolean>>();

/**
 * Bundles a TypeScript extension file into JavaScript using `deno bundle` subprocess.
 *
 * Transpiles TypeScript syntax (interfaces, type annotations, generics) and
 * inlines all npm packages into the bundle. Only `zod` is externalized so that
 * extensions share the same zod instance as swamp (required for schema
 * `instanceof` checks). All other npm packages are resolved and inlined at
 * bundle time, which ensures they work in the compiled binary where only
 * swamp's own embedded dependency graph is available.
 *
 * When `options.selfContained` is true, zod is also inlined, producing a
 * bundle that needs no external modules at all. This is used for Docker
 * execution where the container has no access to swamp's module graph.
 *
 * @param absolutePath - Absolute filesystem path to the TypeScript file
 * @param denoPath - Absolute path to the deno binary to use for bundling
 * @param options - Optional bundle configuration
 * @returns Bundled JavaScript source code as a string
 */
export async function bundleExtension(
  absolutePath: string,
  denoPath: string,
  options?: BundleOptions,
): Promise<string> {
  logger.debug`Bundling extension: ${absolutePath}`;

  const tempFile = await Deno.makeTempFile({
    prefix: "swamp_bundle_",
    suffix: ".js",
  });

  try {
    // When using deno.json, pass --config so the import map governs resolution.
    // When using package.json, use --node-modules-dir=auto so Deno auto-detects
    // package.json via cwd and initializes node_modules/.deno/ if needed (this
    // makes it work with both `npm install` and `deno install`).
    // Otherwise, use --no-lock for the default no-project behavior.
    const args = ["bundle", ...denoProjectArgs(options)];

    // Externalize zod by default so in-process extensions share the
    // host's zod instance (required for `instanceof` schema checks).
    // Self-contained bundles inline everything for out-of-process use.
    if (!options?.selfContained) {
      args.push("--external", "npm:zod@4", "--external", "npm:zod");

      // Every other zod 4 spelling — pinned (npm:zod@4.3.6) or ranged
      // (npm:zod@^4.1, npm:zod@>=4.1 <5), as push ships an import-map target
      // in place of a bare "zod" (swamp-club#3637) — matches only as
      // written, so externalize each one the modules the entry point
      // reaches write.
      for (const spec of await zod4SpecifiersReachedFrom(absolutePath)) {
        args.push("--external", spec);
      }

      // When using a deno.json import map, bare specifier "zod" is resolved
      // to the fully-qualified npm specifier (e.g., "npm:zod@4.3.6") before
      // esbuild sees it. Also externalize the resolved specifier and the
      // bare "zod" specifier. Only do this for zod 4.x — externalizing
      // zod 3.x would silently break since globalThis.__swamp_zod provides zod 4.
      if (options?.denoConfigPath) {
        const resolvedZod = await resolveZodFromConfig(options.denoConfigPath);
        if (resolvedZod) {
          args.push("--external", resolvedZod, "--external", "zod");
        }
      }

      // When using a package.json project, bare specifier "zod" needs to be
      // externalized. Check that the package.json lists zod 4.x before doing so.
      if (options?.packageJsonDir) {
        const isZod4 = await isZod4InPackageJson(options.packageJsonDir);
        if (isZod4) {
          args.push("--external", "zod");
        }
      }
    }

    args.push("--platform", "deno", "-o", tempFile, absolutePath);

    // Each run gets its own timeout, started when it runs: never spent
    // waiting behind the first bundle.
    const runBundle = () =>
      new Deno.Command(denoPath, {
        args,
        stdout: "piped",
        stderr: "piped",
        signal: options?.signal ?? AbortSignal.timeout(BUNDLE_TIMEOUT_MS),
        // For package.json projects, set cwd so Deno auto-detects package.json
        // and resolves bare specifiers from node_modules/.
        ...(options?.packageJsonDir ? { cwd: options.packageJsonDir } : {}),
        ...(options?.env ? { env: options.env } : {}),
      }).output();

    // A bundle that lost an esbuild install race to another process is
    // retried once, inside the gate: a waiter must not start beside it.
    const runWithRetry = async () => {
      const first = await runBundle();
      if (first.success || !isEsbuildInstallRace(outputText(first))) {
        return first;
      }
      logger
        .debug`Retrying bundle of ${absolutePath} after an esbuild install race`;
      return await runBundle();
    };

    // The child's cache: options.env merges over this process's env.
    const denoDir = options?.env?.DENO_DIR ?? Deno.env.get("DENO_DIR") ??
      "";
    const output = await runFirstAlone(firstBundles, denoDir, runWithRetry, {
      signal: options?.signal,
      // Still lost after the retry: the cache may lack esbuild, so the next
      // bundle installs it alone again.
      succeeded: (result) =>
        result.success || !isEsbuildInstallRace(outputText(result)),
    });

    if (!output.success) {
      const lockPath = options?.readOnlyLock?.lockPath;
      if (lockPath && isStaleLockfile(outputText(output))) {
        throw staleLockfileError(
          lockPath,
          absolutePath,
          options,
          outputText(output),
        );
      }
      const rawDetails = outputText(output).trim() ||
        "(no output — try running deno 2.7.x or later)";
      const details = stripAnsiCode(rawDetails);
      throw markErrorPaths(
        new Error(
          `deno bundle failed for ${absolutePath}: ${details}`,
        ),
        [absolutePath],
      );
    }

    let js = await Deno.readTextFile(tempFile);

    if (!js) {
      // Type-only files (interfaces, type aliases) produce empty bundles
      // because TypeScript erases them at compile time. Return a minimal
      // module so the loader can silently skip it (no model/extension export).
      js = "export {};\n";
    }

    // Fix CJS/ESM interop for packages like tslib that set __esModule.
    js = fixCjsEsmInterop(js);

    // Rewrite externalized zod imports to use globalThis.__swamp_zod
    // so extensions share swamp's Zod instance in the compiled binary.
    if (!options?.selfContained) {
      rejectZodV3Imports(js, absolutePath);
      js = rewriteZodImports(js, absolutePath);
    }

    logger.debug`Bundled ${absolutePath} (${js.length} bytes)`;
    return js;
  } finally {
    try {
      await Deno.remove(tempFile);
    } catch {
      // Temp file cleanup is best-effort
    }
  }
}

function outputText(output: Deno.CommandOutput): string {
  const decoder = new TextDecoder();
  return decoder.decode(output.stderr) + decoder.decode(output.stdout);
}
