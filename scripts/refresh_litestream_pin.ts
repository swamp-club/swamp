/** The Docker image's targets, keyed by Docker's TARGETARCH. */
export const DOCKER_TARGETS: Readonly<Record<string, LitestreamTarget>> = {
  amd64: "linux-x86_64",
  arm64: "linux-arm64",
};

/** Parses upstream's `checksums.txt` (`<sha256>  <file name>` per line). */
export function parseChecksumsTxt(text: string): Map<string, string> {
  const checksums = new Map<string, string>();
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (trimmed === "") continue;
    const match = trimmed.match(/^([0-9a-f]{64})\s+\*?(\S+)$/);
    if (match === null) {
      throw new Error(`Unrecognised checksums.txt line: ${line}`);
    }
    checksums.set(match[2], match[1]);
  }
  return checksums;
}

/** Renders `litestream_pin.ts`, already in `deno fmt` style. */
export function renderPinFile(
  version: string,
  targets: Readonly<Record<LitestreamTarget, LitestreamTargetDigests>>,
): string {
  const entries = LITESTREAM_TARGETS.map((target) =>
    [
      `    "${target}": {`,
      `      archiveSha256:`,
      `        "${targets[target].archiveSha256}",`,
      `      binarySha256:`,
      `        "${targets[target].binarySha256}",`,
      `    },`,
    ].join("\n")
  ).join("\n");
  return `${LICENSE_HEADER}
// Generated by scripts/refresh_litestream_pin.ts. Do not edit by hand: run
// \`deno run litestream-pin --version <version>\`, which also rewrites the
// Dockerfile's copy of the linux archive digests.

import { LitestreamPin } from "../../../domain/datastore_v3/litestream_release.ts";

/** The Litestream release this swamp build downloads and runs. */
export const LITESTREAM_PIN: LitestreamPin = LitestreamPin.from({
  version: "${version}",
  targets: {
${entries}
  },
});
`;
}

const DOCKER_ADD =
  /^ADD --checksum=sha256:[0-9a-f]{64} https:\/\/github\.com\/\S+ \/litestream\.tar\.gz$/;

/**
 * Rewrites the Dockerfile's per-arch `ADD --checksum` lines. Each one follows
 * a `FROM scratch AS litestream-<arch>` line. Throws unless both are found.
 */
export function rewriteDockerfilePins(
  dockerfile: string,
  version: string,
  targets: Readonly<Record<LitestreamTarget, LitestreamTargetDigests>>,
): string {
  const lines = dockerfile.split("\n");
  const rewritten = new Set<string>();
  for (let i = 0; i < lines.length - 1; i++) {
    const stage = lines[i].match(/^FROM scratch AS litestream-(\S+)$/);
    if (stage === null) continue;
    const target = DOCKER_TARGETS[stage[1]];
    if (target === undefined || !DOCKER_ADD.test(lines[i + 1])) {
      throw new Error(
        `Dockerfile: stage litestream-${stage[1]} must be followed by an ` +
          `"ADD --checksum=sha256:<digest> <url> /litestream.tar.gz" line`,
      );
    }
    lines[i + 1] = `ADD --checksum=sha256:${
      targets[target].archiveSha256
    } ${litestreamArchiveUrl(version, target)} /litestream.tar.gz`;
    rewritten.add(stage[1]);
  }
  for (const arch of Object.keys(DOCKER_TARGETS)) {
    if (!rewritten.has(arch)) {
      throw new Error(`Dockerfile: no "FROM scratch AS litestream-${arch}" stage`);
    }
  }
  return lines.join("\n");
}

async function download(url: string): Promise<Uint8Array> {
  const response = await fetch(url, { signal: AbortSignal.timeout(300_000) });
  if (!response.ok) {
    await response.body?.cancel();
    throw new Error(`GET ${url}: HTTP ${response.status}`);
  }
  return new Uint8Array(await response.arrayBuffer());
}

/** Reads one file out of a `.tar.gz`, in memory. */
async function readFromTarGz(
  archive: Uint8Array,
  name: string,
): Promise<Uint8Array> {
  const entries = ReadableStream.from([archive])
    .pipeThrough(
      // DecompressionStream is typed to take BufferSource; bytes are fine.
      new DecompressionStream("gzip") as unknown as TransformStream<
        Uint8Array,
        Uint8Array
      >,
    )
    .pipeThrough(new UntarStream());
  let found: Uint8Array | undefined;
  for await (const entry of entries) {
    if (entry.path === name && entry.readable !== undefined) {
      found = new Uint8Array(await new Response(entry.readable).arrayBuffer());
    } else {
      await entry.readable?.cancel();
    }
  }
  if (found === undefined) throw new Error(`${name} not in archive`);
  return found;
}

/** Reads one file out of a `.zip` with the system `unzip`. */
async function readFromZip(
  archive: Uint8Array,
  name: string,
): Promise<Uint8Array> {
  const dir = await Deno.makeTempDir({ prefix: "swamp_litestream_pin_" });
  try {
    const path = join(dir, "archive.zip");
    await Deno.writeFile(path, archive);
    const result = await new Deno.Command("unzip", {
      args: ["-p", path, name],
      stdout: "piped",
      stderr: "piped",
    }).output();
    if (!result.success) {
      throw new Error(
        `unzip -p ${name} failed: ${new TextDecoder().decode(result.stderr)}`,
      );
    }
    return result.stdout;
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
}

/**
 * Downloads every target's archive for `version`, checks it against
 * upstream's `checksums.txt`, and hashes the binary inside.
 */
export async function deriveDigests(
  version: string,
): Promise<Record<LitestreamTarget, LitestreamTargetDigests>> {
  const checksums = parseChecksumsTxt(
    new TextDecoder().decode(
      await download(
        `https://github.com/${LITESTREAM_REPOSITORY}/releases/download/v${version}/checksums.txt`,
      ),
    ),
  );
  const targets: Partial<Record<LitestreamTarget, LitestreamTargetDigests>> =
    {};
  for (const target of LITESTREAM_TARGETS) {
    const name = litestreamArchiveName(version, target);
    const expected = checksums.get(name);
    if (expected === undefined) {
      throw new Error(`checksums.txt for ${version} has no ${name}`);
    }
    const archive = await download(litestreamArchiveUrl(version, target));
    const archiveSha256 = await computeChecksum(archive);
    if (archiveSha256 !== expected) {
      throw new Error(
        `${name}: SHA-256 ${archiveSha256} does not match checksums.txt ${expected}`,
      );
    }
    const binaryName = litestreamBinaryName(target);
    const binary = name.endsWith(".zip")
      ? await readFromZip(archive, binaryName)
      : await readFromTarGz(archive, binaryName);
    // The Dockerfile extracts LICENSE from the linux archives by name, so a
    // release without it must fail here, not in the image build.
    if (!name.endsWith(".zip")) await readFromTarGz(archive, "LICENSE");
    targets[target] = { archiveSha256, binarySha256: await computeChecksum(binary) };
    console.log(`${target}: archive ${archiveSha256}`);
  }
  return targets as Record<LitestreamTarget, LitestreamTargetDigests>;
}

/** The version the checked-in pin file names. */
export function pinnedVersionOf(pinFile: string): string {
  const match = pinFile.match(/^ {2}version: "(\d+\.\d+\.\d+)",$/m);
  if (match === null) throw new Error("No version line in the pin file");
  return match[1];
}

/**
 * Re-derives the pin for `version` and returns the files that differ from
 * what it would render, empty when everything matches upstream.
 */
export async function findDrift(version: string): Promise<string[]> {
  const targets = await deriveDigests(version);
  const drift: string[] = [];
  if (await Deno.readTextFile(PIN_FILE) !== renderPinFile(version, targets)) {
    drift.push(PIN_FILE);
  }
  const dockerfile = await Deno.readTextFile(DOCKERFILE);
  if (dockerfile !== rewriteDockerfilePins(dockerfile, version, targets)) {
    drift.push(DOCKERFILE);
  }
  return drift;
}

async function main(): Promise<void> {
  const args = parseArgs(Deno.args, {
    string: ["version"],
    boolean: ["check"],
  });
  if (args.check) {
    const version = pinnedVersionOf(await Deno.readTextFile(PIN_FILE));
    const drift = await findDrift(version);
    if (drift.length > 0) {
      console.error(
        `Litestream ${version} pin drifts from upstream in: ${drift.join(", ")}`,
      );
      Deno.exit(1);
    }
    console.log(`Litestream ${version} pin matches upstream.`);
    return;
  }
  if (args.version === undefined) {
    console.error("Usage: refresh_litestream_pin.ts --version <x.y.z> | --check");
    Deno.exit(2);
  }
  const version = args.version.replace(/^v/, "");
  const targets = await deriveDigests(version);
  await Deno.writeTextFile(PIN_FILE, renderPinFile(version, targets));
  const dockerfile = await Deno.readTextFile(DOCKERFILE);
  await Deno.writeTextFile(
    DOCKERFILE,
    rewriteDockerfilePins(dockerfile, version, targets),
  );
  console.log(`Pinned Litestream ${version}.`);
}

if (import.meta.main) {
  await main();
}
